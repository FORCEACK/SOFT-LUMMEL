    private void btnResumenSemanalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResumenSemanalActionPerformed
        // TODO add your handling code here:
        // Creamos un pequeño panel con dos calendarios
    javax.swing.JPanel panelSemanal = new javax.swing.JPanel();
    panelSemanal.setLayout(new java.awt.GridLayout(2, 2, 10, 10));

    com.toedter.calendar.JDateChooser fechaInicio = new com.toedter.calendar.JDateChooser();
    com.toedter.calendar.JDateChooser fechaFin = new com.toedter.calendar.JDateChooser();

    panelSemanal.add(new javax.swing.JLabel("De la fecha:"));
    panelSemanal.add(fechaInicio);
    panelSemanal.add(new javax.swing.JLabel("Hasta la fecha:"));
    panelSemanal.add(fechaFin);

   // Mostramos la ventana emergente
    int opcion = javax.swing.JOptionPane.showConfirmDialog(this, panelSemanal, "Seleccionar Semana / Rango", javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.PLAIN_MESSAGE);

    if (opcion == javax.swing.JOptionPane.OK_OPTION) {
    if (fechaInicio.getDate() != null && fechaFin.getDate() != null) {
    java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String fInicio = sdf.format(fechaInicio.getDate());
    String fFin = sdf.format(fechaFin.getDate());
    
    // LLAMAMOS AL CONTROLADOR Y CALCULAMOS EL TOTAL
    CONTROLADOR.ControladorFinanzas controlador = new CONTROLADOR.ControladorFinanzas();
    controlador.buscarVentasPorRango(jTable1, fInicio, fFin);
    calcularTotalTabla();
    }   else {
    javax.swing.JOptionPane.showMessageDialog(this, "Debes seleccionar ambas fechas.");
    }
    }
    }//GEN-LAST:event_btnResumenSemanalActionPerformed

