    public void calcularTotalTabla() {
        double totalGeneral = 0.0;
        // Ojo: Asegúrate de que "jTable1" sea el nombre real de tu tabla
        for (int i = 0; i < jTable1.getRowCount(); i++) { 
            Object valor = jTable1.getValueAt(i, 4); // El 4 es la columna "Total"
            if (valor != null) {
                totalGeneral += Double.parseDouble(valor.toString());
            }
        }
        // Ojo: Asegúrate de que "lblTotalAcomulado" sea el nombre real de tu etiqueta de texto
        lblTotalAcomulado.setText(String.format("$%.2f", totalGeneral)); 
    }

